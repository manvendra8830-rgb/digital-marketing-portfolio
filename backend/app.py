@app.post("/api/contact")
@limiter.limit("5 per minute")
def contact():
    if not request.is_json:
        return jsonify({
            "status": "error",
            "message": "JSON data is required.",
        }), 415

    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({
            "status": "error",
            "message": "Invalid request data.",
        }), 400

    name = clean_text(data.get("name"))
    email = clean_text(data.get("email"))
    service = clean_text(data.get("service"))
    budget = clean_text(data.get("budget"))
    message = clean_text(data.get("message"))

    if not all([name, email, service, message]):
        return jsonify({
            "status": "error",
            "message": "Please complete all required fields.",
        }), 400

    if not 2 <= len(name) <= 80:
        return jsonify({
            "status": "error",
            "message": "Name must contain 2 to 80 characters.",
        }), 400

    if len(email) > 254 or not validate_email(email):
        return jsonify({
            "status": "error",
            "message": "Please enter a valid email address.",
        }), 400

    if service not in ALLOWED_SERVICES:
        return jsonify({
            "status": "error",
            "message": "Invalid service selection.",
        }), 400

    if budget not in ALLOWED_BUDGETS:
        return jsonify({
            "status": "error",
            "message": "Invalid budget selection.",
        }), 400

    if not 10 <= len(message) <= 2000:
        return jsonify({
            "status": "error",
            "message": "Message must contain 10 to 2000 characters.",
        }), 400

    try:
        with get_db() as connection:
            connection.execute(
                """
                INSERT INTO enquiries (name, email, service, budget, message)
                VALUES (%s, %s, %s, %s, %s)
                """,
                (name, email, service, budget, message),
            )

    except psycopg.Error:
        app.logger.exception("Database insert error")
        return jsonify({
            "status": "error",
            "message": "Unable to process your enquiry right now.",
        }), 500

    return jsonify({
        "status": "success",
        "message": "Your enquiry has been submitted successfully.",
    }), 201


def admin_required(function):
    @wraps(function)
    def wrapper(*args, **kwargs):
        if not session.get("admin_logged_in"):
            return jsonify({
                "status": "error",
                "message": "Authentication required.",
            }), 401

        return function(*args, **kwargs)

    return wrapper


@app.route("/api/admin/login", methods=["POST"])
@limiter.limit("5 per minute")
def admin_login():
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({
            "status": "error",
            "message": "Invalid login data.",
        }), 400

    username = data.get("username", "")
    password = data.get("password", "")

    if (
        username != admin_username
        or not isinstance(password, str)
        or not check_password_hash(admin_password_hash, password)
    ):
        return jsonify({
            "status": "error",
            "message": "Invalid username or password.",
        }), 401

    session.clear()
    session["admin_logged_in"] = True
    session.permanent = True

    return jsonify({
        "status": "success",
        "message": "Login successful.",
    }), 200


@app.route("/api/admin/logout", methods=["POST"])
@admin_required
def admin_logout():
    session.clear()

    return jsonify({
        "status": "success",
        "message": "Logged out successfully.",
    })


@app.route("/api/admin/enquiries", methods=["GET"])
@admin_required
def get_admin_enquiries():
    try:
        with get_db() as connection:
            enquiries = connection.execute(
                """
                SELECT id, name, email, service, budget, message, created_at
                FROM enquiries
                ORDER BY created_at DESC
                LIMIT 100
                """
            ).fetchall()

        return jsonify({
            "status": "success",
            "enquiries": [
                {
                    **row,
                    "created_at": (
                        row["created_at"].isoformat()
                        if row["created_at"] else None
                    ),
                }
                for row in enquiries
            ],
        })

    except psycopg.Error:
        app.logger.exception("Database read error")
        return jsonify({
            "status": "error",
            "message": "Unable to retrieve enquiries.",
        }), 500


@app.route("/api/admin/enquiries/<int:enquiry_id>", methods=["DELETE"])
@admin_required
@limiter.limit("20 per minute")
def delete_admin_enquiry(enquiry_id):
    try:
        with get_db() as connection:
            cursor = connection.execute(
                "DELETE FROM enquiries WHERE id = %s",
                (enquiry_id,),
            )

            if cursor.rowcount == 0:
                return jsonify({
                    "status": "error",
                    "message": "Enquiry not found.",
                }), 404

        return jsonify({
            "status": "success",
            "message": "Enquiry deleted successfully.",
        }), 200

    except psycopg.Error:
        app.logger.exception("Database deletion error")
        return jsonify({
            "status": "error",
            "message": "Unable to delete enquiry.",
        }), 500


